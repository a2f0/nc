import type { Catalog } from "./catalog";

/** Native pickers use this same registry as web; no separately maintained language lists. */
export function languageFiles({ locales }: Catalog): Map<string, string> {
  const choices = [
    { tag: "device", nativeName: "", direction: "ltr" },
    ...locales.map(locale => ({
      tag: locale.tag, nativeName: locale.nativeName ?? locale.tag, direction: locale.direction ?? "ltr",
    })),
  ];
  const quote = (value: string) => JSON.stringify(value).replace(/\$/g, "\\$");
  const identifier = (tag: string) => tag.replace(/-/g, "_");
  return new Map([
    ["android/app/src/main/java/net/a2f0/nc/Language.kt", `// Generated by bun run l10n. Edit l10n/locales.ts.
package net.a2f0.nc

enum class Language(val tag: String, val nativeName: String, val rtl: Boolean) {
${choices.map(c => `    ${identifier(c.tag).toUpperCase()}(${quote(c.tag)}, ${quote(c.nativeName)}, ${c.direction === "rtl"})`).join(",\n")};

    companion object {
        fun fromTag(tag: String?): Language = entries.find { it.tag == tag } ?: DEVICE
    }
}
`],
    ["ios/Shared/AppLanguage.swift", `// Generated by bun run l10n. Edit l10n/locales.ts.
import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
${choices.map(c => `    case \`${identifier(c.tag)}\` = ${JSON.stringify(c.tag)}`).join("\n")}
    var id: String { rawValue }
    var nativeName: String {
        switch self {
${choices.map(c => `        case .\`${identifier(c.tag)}\`: ${JSON.stringify(c.nativeName)}`).join("\n")}
        }
    }
    var isRTL: Bool {
        switch self {
${choices.map(c => `        case .\`${identifier(c.tag)}\`: ${c.direction === "rtl"}`).join("\n")}
        }
    }
}
`],
  ]);
}
